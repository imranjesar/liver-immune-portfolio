suppressPackageStartupMessages({library(Seurat);library(ggplot2);library(patchwork)})
set.seed(20261103)
source("scripts/settings.R")
files <- read.delim("config/sc_samples.tsv", stringsAsFactors=FALSE)
objects <- lapply(seq_len(nrow(files)), function(i) {
  d <- files[i,]; path <- file.path("data/processed", d$matrix_dir)
  x <- ReadMtx(file.path(path,"matrix.mtx.gz"), file.path(path,"barcodes.tsv.gz"),
               file.path(path,"features.tsv.gz"), feature.column=1)
  s <- CreateSeuratObject(x, project=d$sample_id, min.cells=3)
  s$sample_id <- d$sample_id; s$condition <- d$condition
  s <- RenameCells(s, add.cell.id=d$sample_id)
  s[["percent.mt"]] <- PercentageFeatureSet(s, pattern="^mt-")
  s
})
obj <- merge(objects[[1]], y=objects[-1])
dir.create("results/sc", recursive=TRUE, showWarnings=FALSE)
write.csv(obj[[]],"results/sc/qc_before.csv")
pdf("results/sc/qc_before.pdf",width=12,height=5)
print(VlnPlot(obj,features=c("nFeature_RNA","nCount_RNA","percent.mt"),group.by="sample_id",pt.size=0));dev.off()
obj <- subset(obj, subset=nFeature_RNA >= min_features & nFeature_RNA <= max_features & percent.mt <= max_mt)
stopifnot(length(unique(obj$sample_id))==nrow(files))
obj <- NormalizeData(obj,verbose=FALSE)
obj <- FindVariableFeatures(obj,nfeatures=2000,verbose=FALSE)
obj <- ScaleData(obj,features=VariableFeatures(obj),verbose=FALSE)
obj <- RunPCA(obj,npcs=30,verbose=FALSE)
obj <- FindNeighbors(obj,dims=1:20,verbose=FALSE)
obj <- FindClusters(obj,resolution=0.4,random.seed=20261103,verbose=FALSE)
obj <- RunUMAP(obj,dims=1:20,seed.use=20261103,verbose=FALSE)
obj <- JoinLayers(obj)
pdf("results/sc/umap.pdf",width=12,height=5)
print(DimPlot(obj,group.by="seurat_clusters",label=TRUE,shuffle=TRUE,seed=20261103)+DimPlot(obj,group.by="condition",shuffle=TRUE,seed=20261103));dev.off()
saveRDS(obj,"results/sc/seurat.rds")
write.csv(obj[[]],"results/sc/qc_after.csv")
markers <- FindAllMarkers(obj,only.pos=TRUE,min.pct=0.25,logfc.threshold=0.25,verbose=FALSE)
write.csv(markers,"results/sc/exploratory_cluster_markers.csv",row.names=FALSE)
write.csv(as.data.frame(table(obj$sample_id,Idents(obj))),"results/sc/sample_cluster_counts.csv",row.names=FALSE)
pdf("results/sc/immune_markers.pdf",width=12,height=6)
print(DotPlot(obj,features=intersect(c("Cd3d","Cd3e","Ms4a1","Cd79a","Nkg7","Ccl5","Lyz2","Adgre1","Csf1r","S100a8","S100a9","Ly6g","Itgax","Flt3"),rownames(obj)))+RotatedAxis());dev.off()
writeLines(capture.output(sessionInfo()),"results/sc/sessionInfo.txt")
