suppressPackageStartupMessages({library(Seurat);library(Matrix);library(jsonlite)})
cfg<-jsonlite::fromJSON("config/pseudobulk.json")
write_csv_gz<-function(x,path){con<-gzfile(path,"wt");on.exit(close(con));write.csv(x,con,row.names=FALSE)}
path<-"results/sc/pseudobulk";dir.create(path,recursive=TRUE,showWarnings=FALSE)
if(file.exists(file.path(path,"AGGREGATION_COMPLETE")))unlink(file.path(path,"AGGREGATION_COMPLETE"))
s<-readRDS("results/sc/strict500_consensus/seurat.rds")
a<-read.csv(gzfile("results/sc/strict500_consensus/cell_annotations.csv.gz"),stringsAsFactors=FALSE)
f<-read.csv("results/sc/review/cell_lineage_coexpression.csv",stringsAsFactors=FALSE)
pops<-read.delim("config/pseudobulk_populations.tsv",stringsAsFactors=FALSE)
samples<-read.delim("config/sc_samples.tsv",stringsAsFactors=FALSE)
stopifnot(!anyDuplicated(a$cell_id),!anyDuplicated(f$cell_id),setequal(a$cell_id,colnames(s)))
a<-a[match(colnames(s),a$cell_id),];idx<-match(a$cell_id,f$cell_id);stopifnot(!anyNA(idx))
a$strong_B_T_screen<-f$B_T_strong_screen[idx]
a$population<-NA_character_
for(i in seq_len(nrow(pops))){cl<-strsplit(pops$clusters[i],",",fixed=TRUE)[[1]];sel<-as.character(a$seurat_clusters)%in%cl;stopifnot(all(is.na(a$population[sel])));a$population[sel]<-pops$population[i]}
a$exclusion_reason<-ifelse(is.na(a$population),"outside_prespecified_reviewed_populations",ifelse(a$confidence!="high","lineage_confidence_not_high",ifelse(a$baseline_review_hold|a$new_cluster_hold,"unresolved_review_hold",ifelse(a$rate_sensitive_call,"rate_sensitive_doublet_call",ifelse(a$strong_B_T_screen,"strong_B_T_marker_conflict","included")))))
a$included<-a$exclusion_reason=="included"
write_csv_gz(a[,c("cell_id","sample_id","condition","seurat_clusters","population","included","exclusion_reason","strong_B_T_screen","needs_further_review")],file.path(path,"cell_selection.csv.gz"))
keep<-which(a$included);meta<-expand.grid(sample_id=samples$sample_id,population=pops$population,stringsAsFactors=FALSE)
meta$aggregate_id<-paste(meta$population,meta$sample_id,sep="__")
meta$condition<-samples$condition[match(meta$sample_id,samples$sample_id)];meta$capture<-samples$gsm[match(meta$sample_id,samples$sample_id)]
group<-match(paste(a$population[keep],a$sample_id[keep],sep="__"),meta$aggregate_id);stopifnot(!anyNA(group))
counts<-GetAssayData(s,layer="counts")
selected<-counts[,keep,drop=FALSE]
G<-sparseMatrix(i=seq_along(keep),j=group,x=1,dims=c(length(keep),nrow(meta)))
pb<-as.matrix(selected%*%G);colnames(pb)<-meta$aggregate_id
stopifnot(all(pb>=0),all(pb==round(pb)),all(is.finite(pb)),all(rowSums(pb)==Matrix::rowSums(selected)))
meta$n_cells<-tabulate(group,nbins=nrow(meta));meta$total_umi<-colSums(pb)
stopifnot(sum(meta$n_cells)==length(keep),sum(pb)==sum(selected))
storage.mode(pb)<-"integer"
write.csv(meta,file.path(path,"sample_cell_counts.csv"),row.names=FALSE)
write_csv_gz(data.frame(gene=rownames(pb),pb,check.names=FALSE),file.path(path,"raw_pseudobulk_counts.csv.gz"))
saveRDS(list(counts=pb,samples=meta,config=cfg,populations=pops),file.path(path,"aggregates.rds"))
summary<-as.data.frame(table(a$exclusion_reason));names(summary)<-c("reason","cells")
write.csv(summary,file.path(path,"selection_summary.csv"),row.names=FALSE)
checks<-data.frame(check=c("included_cells","aggregated_umi","gene_wise_sum_preserved","all_samples_preserved"),value=c(length(keep),sum(pb),1,length(unique(meta$sample_id))))
write.csv(checks,file.path(path,"aggregation_checks.csv"),row.names=FALSE)
jsonlite::write_json(list(config=cfg,annotation_sha256=digest::digest(file="results/sc/strict500_consensus/cell_annotations.csv.gz",algo="sha256"),input_sha256=digest::digest(file="results/sc/strict500_consensus/seurat.rds",algo="sha256"),population_map_sha256=digest::digest(file="config/pseudobulk_populations.tsv",algo="sha256")),file.path(path,"provenance.json"),auto_unbox=TRUE,pretty=TRUE)
writeLines(capture.output(sessionInfo()),file.path(path,"aggregation_sessionInfo.txt"))
writeLines("COMPLETE",file.path(path,"AGGREGATION_COMPLETE"))
cat("Included",length(keep),"cells in",ncol(pb),"population-by-mouse aggregates\n")
