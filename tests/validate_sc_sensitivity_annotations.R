a<-read.csv(gzfile("results/sc/strict500_consensus/cell_annotations.csv.gz"),stringsAsFactors=FALSE)
m<-read.csv("results/sc/strict500_consensus/cell_metadata.csv",stringsAsFactors=FALSE)
map<-read.delim("config/celltypes_consensus.tsv",colClasses="character")
guard<-jsonlite::fromJSON("config/celltypes_consensus_signature.json")
stopifnot(!anyDuplicated(a$cell_id),setequal(a$cell_id,m$cell_id),!anyNA(a$cell_type),nrow(map)==length(unique(m$seurat_clusters)))
i<-match(as.character(a$seurat_clusters),map$cluster)
stopifnot(!anyNA(i),all(a$cell_type==map$cell_type[i]),all(a$needs_further_review==(a$baseline_review_hold|a$new_cluster_hold|a$rate_sensitive_call)))
stopifnot(all(a$new_cluster_hold[a$seurat_clusters %in% c(5,23)]))
h<-digest::digest(data.frame(cell_id=m$cell_id,cluster=as.character(m$seurat_clusters)),algo="sha256")
stopifnot(identical(h,guard$cluster_assignment_sha256))
run<-jsonlite::fromJSON("results/sc/doublets/run_parameters.json")
lock<-jsonlite::fromJSON("renv.lock",simplifyVector=FALSE)
for(n in names(run$dependencies))stopifnot(identical(run$dependencies[[n]],lock$Packages[[n]]$Version))
